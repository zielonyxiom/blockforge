#!/usr/bin/env node
// Deep analysis of reference trees: per-tree structure (roots, collar, trunk, branches,
// canopy blobs, details) and the house statistics over all of them.
// Usage: node scripts/analyze-trees.mjs [dir=training/studio-trees] [out=training/analysis]
import fs from 'node:fs';
import path from 'node:path';
import { analyzeTree, summarize } from '../server/analyze.js';

const dir = process.argv[2] || 'training/studio-trees';
const out = process.argv[3] || 'training/analysis';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'index.json');
const trees = files.map((f) => ({ file: f, ...analyzeTree(JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'))) }));
const stats = summarize(trees.map(({ file, ...a }) => a));
fs.mkdirSync(out, { recursive: true });
fs.writeFileSync(path.join(out, 'trees.json'), JSON.stringify(trees, null, 1));
fs.writeFileSync(path.join(out, 'stats.json'), JSON.stringify(stats, null, 1));

const row = (t) => `| ${t.file.replace(/\.json$/, '')} | ${t.parts} | ${t.size.join('×')} | ${t.footprint} | ${t.trunk.segments} | ${t.trunk.base_width}→${t.trunk.top_width} | ${t.trunk.bare_ratio} | ${t.collar} | ${t.roots.count} (${t.roots.two_part} two-part, ${t.roots.directions} dirs) | ${t.roots.slope_median ?? '–'}° | ${t.canopy.start_ratio} | ${t.canopy.blobs} | ${t.canopy.plates_per_blob} | ${t.details.count} (${t.details.front}/${t.details.back}) |`;
const s = (k) => `${stats[k].median} (${stats[k].p25}–${stats[k].p75})`;
const md = `# Tree analysis (${trees.length} models from ${dir})

Generated by \`node scripts/analyze-trees.mjs\`. Roles are detected from colors and geometry: wood = the main
color of the lower half, canopy = the main non-wood color of the upper half; roots = low tilted wood parts away
from the trunk axis; collar = a low wide wood block on the axis; trunk = upright wood under the canopy;
branches = other wood; details = everything else.

## House statistics (median, p25–p75)
| Metric | Value |
|---|---|
| parts | ${s('parts')} |
| footprint (narrow / wide side) | ${s('footprint')} |
| height / width | ${s('height_width')} |
| share of tilted parts | ${s('tilted_share')} |
| trunk segments | ${s('trunk.segments')} |
| trunk taper per segment | ${s('trunk.taper')} |
| trunk base width (× tree width) | ${s('trunk.width_rel')} |
| bare trunk (× height) | ${s('trunk.bare_ratio')} |
| root parts | ${s('roots.count')} |
| root slope below horizontal (°) | ${s('roots.slope_median')} |
| root reach (× trunk width) | ${s('roots.reach_rel')} |
| canopy starts at (× height) | ${s('canopy.start_ratio')} |
| canopy blobs | ${s('canopy.blobs')} |
| face plates per blob | ${s('canopy.plates_per_blob')} |
| plate thickness | ${s('canopy.plate_thickness')} |
| details | ${s('details.count')} |

Trees with roots (≥2 root parts): ${trees.filter((t) => t.roots.count >= 2).length} / ${trees.length}; with a collar: ${trees.filter((t) => t.collar).length}; with flat base slabs: ${trees.filter((t) => t.base_slabs).length}.

## Per tree
| Tree | Parts | Size | Footprint | Trunk segs | Trunk width | Bare trunk | Collar | Roots | Root slope | Canopy start | Blobs | Plates/blob | Details (front/back) |
|---|---|---|---|---|---|---|---|---|---|---|---|---|---|
${trees.map(row).join('\n')}
`;
fs.writeFileSync(path.join(out, 'ANALYSIS.md'), md);
console.log(`Analyzed ${trees.length} trees → ${out}/ANALYSIS.md, trees.json, stats.json`);
